"""Google OAuth and privacy-preserving usage statistics for Automation AI.

Only account metadata and aggregate usage counts are stored.
Chat questions, answers and conversation histories are never stored here.
"""
from __future__ import annotations

import os
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path

import psycopg
from psycopg.rows import dict_row
from authlib.integrations.starlette_client import OAuth
from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent
load_dotenv(BASE_DIR / ".env")

DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
OAUTH_CLIENT_ID = os.getenv("GOOGLE_CLIENT_ID", "")
OAUTH_CLIENT_SECRET = os.getenv("GOOGLE_CLIENT_SECRET", "")
ADMIN_EMAIL = os.getenv("ADMIN_EMAIL", "").strip().casefold()
DAILY_LIMIT = max(1, int(os.getenv("DAILY_REQUEST_LIMIT", "30")))

oauth = OAuth()
oauth.register(
    name="google",
    client_id=OAUTH_CLIENT_ID,
    client_secret=OAUTH_CLIENT_SECRET,
    server_metadata_url="https://accounts.google.com/.well-known/openid-configuration",
    client_kwargs={"scope": "openid email profile"},
)


@contextmanager
def database():
    """Open a PostgreSQL connection and commit/rollback automatically."""
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is missing from .env")

    # Connection is closed automatically; transactions commit on success.
    with psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=15) as db:
        yield db


def initialize_database() -> None:
    """Create tables if necessary, without deleting any existing rows."""
    with database() as db:
        db.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                google_sub TEXT NOT NULL UNIQUE,
                email TEXT NOT NULL,
                name TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                last_login_at TIMESTAMPTZ,
                last_active_at TIMESTAMPTZ,
                login_count BIGINT NOT NULL DEFAULT 0,
                request_count BIGINT NOT NULL DEFAULT 0
            )
        """)
        db.execute("""
            CREATE TABLE IF NOT EXISTS daily_usage (
                user_id BIGINT NOT NULL REFERENCES users(id),
                day_utc DATE NOT NULL,
                requests BIGINT NOT NULL DEFAULT 0,
                PRIMARY KEY (user_id, day_utc)
            )
        """)


def upsert_google_user(profile: dict) -> dict:
    """Save an authenticated Google user, or update their login information."""
    subject = str(profile["sub"])
    email = str(profile["email"]).strip().casefold()
    name = str(profile.get("name") or email.split("@")[0])

    with database() as db:
        row = db.execute("""
            INSERT INTO users (
                google_sub, email, name, last_login_at, last_active_at, login_count
            )
            VALUES (%s, %s, %s, NOW(), NOW(), 1)
            ON CONFLICT (google_sub) DO UPDATE SET
                email = EXCLUDED.email,
                name = EXCLUDED.name,
                last_login_at = NOW(),
                last_active_at = NOW(),
                login_count = users.login_count + 1
            RETURNING id, google_sub, email, name
        """, (subject, email, name)).fetchone()
        return dict(row)


def find_user(user_id: int | None) -> dict | None:
    if not isinstance(user_id, int) or isinstance(user_id, bool):
        return None

    with database() as db:
        row = db.execute("""
            SELECT id, google_sub, email, name
            FROM users
            WHERE id = %s
        """, (user_id,)).fetchone()
        return dict(row) if row else None


def is_admin(user: dict) -> bool:
    return bool(ADMIN_EMAIL) and user["email"].casefold() == ADMIN_EMAIL


def remaining_today(user_id: int) -> int:
    day_utc = datetime.now(timezone.utc).date()

    with database() as db:
        row = db.execute("""
            SELECT requests
            FROM daily_usage
            WHERE user_id = %s AND day_utc = %s
        """, (user_id, day_utc)).fetchone()
        return max(0, DAILY_LIMIT - (row["requests"] if row else 0))


def record_successful_request(user_id: int) -> None:
    """Count a successful request without recording its text."""
    day_utc = datetime.now(timezone.utc).date()

    with database() as db:
        db.execute("""
            INSERT INTO daily_usage (user_id, day_utc, requests)
            VALUES (%s, %s, 1)
            ON CONFLICT (user_id, day_utc)
            DO UPDATE SET requests = daily_usage.requests + 1
        """, (user_id, day_utc))
        db.execute("""
            UPDATE users
            SET request_count = request_count + 1,
                last_active_at = NOW()
            WHERE id = %s
        """, (user_id,))


def admin_statistics() -> dict:
    """Return user details and aggregate counts only (no chat content)."""
    with database() as db:
        totals = db.execute("""
            SELECT COUNT(*) AS registered_users,
                   COALESCE(SUM(request_count), 0)::BIGINT AS total_requests,
                   COUNT(*) FILTER (
                       WHERE last_active_at >= NOW() - INTERVAL '7 days'
                   ) AS active_last_7_days
            FROM users
        """).fetchone()
        users = db.execute("""
            SELECT name, email,
                   TO_CHAR(created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') AS created_at,
                   TO_CHAR(last_login_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') AS last_login_at,
                   TO_CHAR(last_active_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') AS last_active_at,
                   login_count, request_count
            FROM users
            ORDER BY last_login_at DESC NULLS LAST
            LIMIT 200
        """).fetchall()
        return {
            "summary": dict(totals),
            "users": [dict(row) for row in users],
        }
